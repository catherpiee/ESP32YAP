# Builds include/assets.h: the text font, the heart, nine stars and the grumpy cat logo, as bitmaps the board draws.
# Re-run after changing the font or sizes:   python3 tools/make_assets.py
# Needs Pillow:                               pip install pillow
#
# Want a different font? Put a .ttf/.otf in fonts/ and change FONT_FILE and FONT_SIZE below.
# Keep FONT_SIZE so a short word fits across 288 px; longer text scrolls automatically.
import math
import os
import random

from PIL import Image, ImageDraw, ImageFont

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FONT_FILE = os.path.join(ROOT, "fonts", "Archivo-Black-latin.ttf")
FONT_SIZE = 60
STAR_SIZES = [28, 22, 18, 14, 12, 26, 16, 20, 10]
CAT_HEIGHT = 30
HEART_SIZE = 44
CHARS = [chr(c) for c in range(32, 127)] + ["–", "—", "’"]

out = ["// Generated by tools/make_assets.py. Do not edit; change the script and run it again.",
       "#pragma once", "#include <Arduino.h>",
       "struct Glyph { uint16_t cp; int8_t xoff, yoff; uint8_t w, h, adv; uint32_t off; };",
       "struct Font { uint8_t ascent, capTop, capH; uint16_t count; const Glyph* glyphs; const uint8_t* data; };",
       "struct Mask { uint16_t w, h; const uint8_t* alpha; };"]


def array(name, data):
    out.append(f"static const uint8_t {name}[{len(data)}] PROGMEM = {{")
    for i in range(0, len(data), 40):
        out.append("  " + ",".join(map(str, data[i:i + 40])) + ",")
    out.append("};")


def smooth(img, k):
    """Shrink a k-times oversized drawing for smooth edges."""
    return img.resize((round(img.width / k), round(img.height / k)), Image.LANCZOS)


# ---------- font ----------
font = ImageFont.truetype(FONT_FILE, FONT_SIZE)
ascent = font.getmetrics()[0]
hb = font.getbbox("H", anchor="ls")
data, glyphs = bytearray(), []
for ch in CHARS:
    adv = round(font.getlength(ch))
    box = font.getbbox(ch, anchor="ls")
    w, h = max(0, box[2] - box[0]), max(0, box[3] - box[1])
    if ch == " " or not w or not h:
        glyphs.append((ord(ch), 0, 0, 0, 0, adv, len(data)))
        continue
    img = Image.new("L", (w, h), 0)
    ImageDraw.Draw(img).text((-box[0], -box[1]), ch, font=font, fill=255, anchor="ls")
    glyphs.append((ord(ch), box[0], ascent + box[1], w, h, adv, len(data)))
    data += img.tobytes()
array("font_data", data)
out.append(f"static const Glyph font_glyphs[{len(glyphs)}] = {{")
out += ["  {%d,%d,%d,%d,%d,%d,%d}," % g for g in glyphs]
out.append("};")
out.append(f"static const Font TEXT_FONT = {{{ascent},{ascent + hb[1]},{hb[3] - hb[1]},{len(glyphs)},font_glyphs,font_data}};")

# ---------- heart (typed as <3 or the heart emoji) ----------
k = 8
s = HEART_SIZE * k
img = Image.new("L", (s, s), 0)
d = ImageDraw.Draw(img)
r = s * 0.27
d.ellipse((s * 0.5 - 2 * r, s * 0.1, s * 0.5, s * 0.1 + 2 * r), fill=255)
d.ellipse((s * 0.5, s * 0.1, s * 0.5 + 2 * r, s * 0.1 + 2 * r), fill=255)
d.polygon([(s * 0.5 - 2 * r + s * 0.015, s * 0.1 + r * 1.25), (s * 0.5 + 2 * r - s * 0.015, s * 0.1 + r * 1.25), (s * 0.5, s * 0.92)], fill=255)
heart = smooth(img, k)
array("heart_alpha", heart.tobytes())
out.append(f"static const Mask HEART = {{{heart.width},{heart.height},heart_alpha}};")

# ---------- stars ----------
names = []
for i, size in enumerate(STAR_SIZES):
    rnd = random.Random(i)
    big = size * k
    rot = rnd.uniform(-0.35, 0.35)
    pts = []
    for j in range(10):
        rr = big / 2 if j % 2 == 0 else big / 2 * 0.45
        a = -math.pi / 2 + rot + j * math.pi / 5
        pts.append((big / 2 + rr * math.cos(a), big / 2 + 0.06 * big + rr * math.sin(a)))
    img = Image.new("L", (big, big), 0)
    ImageDraw.Draw(img).polygon(pts, fill=255)
    star = smooth(img, k)
    array(f"star{i}_alpha", star.tobytes())
    names.append(f"{{{star.width},{star.height},star{i}_alpha}}")
out.append(f"static const Mask STARS[{len(names)}] = {{" + ",".join(names) + "};")

# ---------- grumpy cat logo (from the Gesture Meme Cam logo, cat_logo.svg) ----------
k = 4
sc = CAT_HEIGHT * k / 230
big = Image.new("L", (round(300 * sc), round(240 * sc)), 0)
d = ImageDraw.Draw(big)
w = round(20 * sc)
P = lambda x, y: ((x + 10 - 50) * sc, (y - 6 - 90) * sc)
for line in [[(100, 152), (108, 104), (150, 128)], [(244, 128), (290, 116), (292, 160)], [(104, 183), (160, 190)],
             [(236, 187), (288, 187)], [(168, 268), (198, 214), (234, 266)]]:
    d.line([P(*p) for p in line], fill=255, width=w, joint="curve")
    for p in (line[0], line[-1]):
        x, y = P(*p)
        d.ellipse((x - w / 2, y - w / 2, x + w / 2, y + w / 2), fill=255)
x0, y0 = P(58, 122)
x1, y1 = P(322, 314)
d.ellipse((x0, y0, x1, y1), outline=255, width=w)
cat = smooth(big.crop(big.getbbox()), k)
array("cat_alpha", cat.tobytes())
out.append(f"static const Mask CAT = {{{cat.width},{cat.height},cat_alpha}};")

open(os.path.join(ROOT, "include", "assets.h"), "w").write("\n".join(out) + "\n")
print("wrote include/assets.h")
